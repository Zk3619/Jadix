//! Build-time helpers for Lucide glyph/path phf maps and animated recipe codegen.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use serde::Deserialize;
use serde_json::Value;

fn parse_flat_string_map(path: &Path) -> BTreeMap<String, String> {
    let json = fs::read_to_string(path).unwrap_or_else(|e| {
        panic!("failed to read {}: {e}", path.display());
    });
    serde_json::from_str(&json).unwrap_or_else(|e| {
        panic!("failed to parse {} as flat string map: {e}", path.display());
    })
}

/// Valid Rust string literal expression (handles embedded `"` in SVG paths).
fn rust_str_lit(s: &str) -> String {
    serde_json::to_string(s).expect("rust string literal")
}

pub fn write_glyph_map(path: &Path, out: &Path) {
    let map = parse_flat_string_map(path);
    let mut builder = phf_codegen::Map::new();
    for (k, v) in &map {
        builder.entry(k, &rust_str_lit(v));
    }
    let body = builder.build();
    let src = format!(
        "// @generated by build.rs — do not edit\n\
         pub(crate) static LUCIDE_GLYPHS: phf::Map<&'static str, &'static str> =\n{body};\n"
    );
    fs::write(out, src).expect("write lucide_glyph_map.rs");
}

pub fn write_paths_map(path: &Path, out: &Path) {
    let map = parse_flat_string_map(path);
    let mut builder = phf_codegen::Map::new();
    for (k, v) in &map {
        builder.entry(k, &rust_str_lit(v));
    }
    let body = builder.build();
    let src = format!(
        "// @generated by build.rs — do not edit\n\
         pub(crate) static LUCIDE_PATHS: phf::Map<&'static str, &'static str> =\n{body};\n"
    );
    fs::write(out, src).expect("write lucide_paths_map.rs");
}

// --- Animated recipe JSON (build-time only) ---------------------------------

#[derive(Debug, Deserialize)]
struct JsonRecipe {
    id: String,
    #[serde(default)]
    lucide: String,
    #[serde(default = "default_vb", alias = "viewBox")]
    view_box: String,
    #[serde(default = "default_sw", alias = "strokeWidth")]
    stroke_width: f32,
    #[serde(default = "default_cap", alias = "strokeLinecap")]
    stroke_linecap: String,
    #[serde(default = "default_join", alias = "strokeLinejoin")]
    stroke_linejoin: String,
    #[serde(default)]
    root: JsonNodeGroup,
    #[serde(default)]
    nodes: Vec<JsonNode>,
    #[serde(default)]
    animated: bool,
}

fn default_vb() -> String {
    "0 0 24 24".into()
}
fn default_sw() -> f32 {
    2.0
}
fn default_cap() -> String {
    "round".into()
}
fn default_join() -> String {
    "round".into()
}

#[derive(Debug, Default, Deserialize)]
struct JsonNodeGroup {
    #[serde(default)]
    tracks: Vec<JsonTrack>,
}

#[derive(Debug, Default, Deserialize)]
struct JsonNode {
    #[serde(default)]
    id: String,
    #[serde(default = "default_path_tag")]
    tag: String,
    #[serde(default)]
    attrs: BTreeMap<String, String>,
    #[serde(default)]
    tracks: Vec<JsonTrack>,
    #[serde(default)]
    children: Vec<JsonNode>,
}

fn default_path_tag() -> String {
    "path".into()
}

#[derive(Debug, Default, Deserialize)]
struct JsonTrack {
    prop: String,
    #[serde(default)]
    keyframes: BTreeMap<String, Value>,
    #[serde(default)]
    transition: Option<JsonTransition>,
}

#[derive(Debug, Default, Deserialize)]
struct JsonTransition {
    #[serde(default)]
    duration: Option<f32>,
    #[serde(default)]
    delay: Option<f32>,
    #[serde(default)]
    ease: Option<String>,
    #[serde(default)]
    repeat: Option<f32>,
    #[serde(default, rename = "type")]
    ty: Option<String>,
    #[serde(default)]
    stiffness: Option<f32>,
    #[serde(default)]
    damping: Option<f32>,
    #[serde(default)]
    times: Option<Vec<f32>>,
    #[serde(default, rename = "perProp")]
    per_prop: Option<BTreeMap<String, JsonPerProp>>,
}

#[derive(Debug, Default, Deserialize)]
struct JsonPerProp {
    #[serde(default)]
    duration: Option<f32>,
}

pub fn write_animated_recipes(path: &Path, out: &Path) {
    let json = fs::read_to_string(path).unwrap_or_else(|e| {
        panic!("failed to read {}: {e}", path.display());
    });
    let all: BTreeMap<String, JsonRecipe> = serde_json::from_str(&json).unwrap_or_else(|e| {
        panic!("failed to parse {}: {e}", path.display());
    });

    let entries: Vec<(String, JsonRecipe)> = all.into_iter().collect();

    const CHUNK: usize = 20;
    let mut out_src = String::from(
        "// @generated by build.rs — do not edit\n\
         use std::collections::HashMap;\n\
         use std::sync::OnceLock;\n\n\
         use super::{\n\
             AnimatedIconRecipe, KeyframeValue, PerPropTransition, RecipeNode, RecipeNodeGroup,\n\
             RecipeTrack, RecipeTransition,\n\
         };\n\n\
         pub(crate) fn recipes() -> &'static HashMap<String, AnimatedIconRecipe> {\n\
             static MAP: OnceLock<HashMap<String, AnimatedIconRecipe>> = OnceLock::new();\n\
             MAP.get_or_init(|| {\n\
                 let mut m = HashMap::new();\n",
    );

    for (chunk_idx, _) in entries.chunks(CHUNK).enumerate() {
        out_src.push_str(&format!("                push_recipes_{chunk_idx}(&mut m);\n"));
    }

    out_src.push_str("                m\n            })\n}\n");

    for (chunk_idx, chunk) in entries.chunks(CHUNK).enumerate() {
        out_src.push_str(&format!(
            "\n#[inline(never)]\nfn push_recipes_{chunk_idx}(m: &mut HashMap<String, AnimatedIconRecipe>) {{\n"
        ));
        for (name, recipe) in chunk {
            out_src.push_str(&format!("    m.insert({name:?}.into(), {});\n", emit_recipe(recipe)));
        }
        out_src.push_str("}\n");
    }

    fs::write(out, out_src).expect("write lucide_animated_recipes.rs");
}

fn emit_f32(v: f32) -> String {
    format!("{v}_f32")
}

fn emit_opt_f32(v: Option<f32>) -> String {
    match v {
        None => "None".into(),
        Some(x) => format!("Some({x}_f32)"),
    }
}

fn emit_f32_vec(v: &Option<Vec<f32>>) -> String {
    match v {
        None => "None".into(),
        Some(xs) if xs.is_empty() => "None".into(),
        Some(xs) => {
            let items = xs.iter().map(|x| emit_f32(*x)).collect::<Vec<_>>().join(", ");
            format!("Some(vec![{items}])")
        }
    }
}

fn emit_str(s: &str) -> String {
    format!("{s:?}.into()")
}

fn emit_opt_str(s: &Option<String>) -> String {
    match s {
        None => "None".into(),
        Some(v) => format!("Some({v:?}.into())"),
    }
}

fn emit_recipe(r: &JsonRecipe) -> String {
    format!(
        "AnimatedIconRecipe {{ id: {}, lucide: {}, view_box: {}, stroke_width: {}, stroke_linecap: {}, stroke_linejoin: {}, root: {}, nodes: vec![{}], animated: {} }}",
        emit_str(&r.id),
        emit_str(&r.lucide),
        emit_str(&r.view_box),
        emit_f32(r.stroke_width),
        emit_str(&r.stroke_linecap),
        emit_str(&r.stroke_linejoin),
        emit_node_group(&r.root),
        r.nodes.iter().map(emit_node).collect::<Vec<_>>().join(", "),
        r.animated,
    )
}

fn emit_node_group(g: &JsonNodeGroup) -> String {
    format!(
        "RecipeNodeGroup {{ tracks: vec![{}] }}",
        g.tracks.iter().map(emit_track).collect::<Vec<_>>().join(", ")
    )
}

fn emit_node(n: &JsonNode) -> String {
    format!(
        "RecipeNode {{ id: {}, tag: {}, attrs: {}, tracks: vec![{}], children: vec![{}] }}",
        emit_str(&n.id),
        emit_str(&n.tag),
        emit_string_map(&n.attrs),
        n.tracks.iter().map(emit_track).collect::<Vec<_>>().join(", "),
        n.children.iter().map(emit_node).collect::<Vec<_>>().join(", ")
    )
}

fn emit_string_map(m: &BTreeMap<String, String>) -> String {
    if m.is_empty() {
        return "HashMap::new()".into();
    }
    let pairs = m
        .iter()
        .map(|(k, v)| format!("({k:?}.into(), {v:?}.into())"))
        .collect::<Vec<_>>()
        .join(", ");
    format!("HashMap::from([{pairs}])")
}

fn emit_track(t: &JsonTrack) -> String {
    let kf = t
        .keyframes
        .iter()
        .map(|(k, v)| format!("({k:?}.into(), {})", emit_keyframe_value(v)))
        .collect::<Vec<_>>()
        .join(", ");
    let transition = match &t.transition {
        None => "None".into(),
        Some(tr) => format!(
            "Some(RecipeTransition {{ duration: {}, delay: {}, ease: {}, repeat: {}, ty: {}, stiffness: {}, damping: {}, times: {}, per_prop: {} }})",
            emit_opt_f32(tr.duration),
            emit_opt_f32(tr.delay),
            emit_opt_str(&tr.ease),
            emit_opt_f32(tr.repeat),
            emit_opt_str(&tr.ty),
            emit_opt_f32(tr.stiffness),
            emit_opt_f32(tr.damping),
            emit_f32_vec(&tr.times),
            emit_per_prop_map(tr.per_prop.as_ref()),
        ),
    };
    format!(
        "RecipeTrack {{ prop: {}, keyframes: HashMap::from([{kf}]), transition: {transition} }}",
        emit_str(&t.prop)
    )
}

fn emit_per_prop_map(m: Option<&BTreeMap<String, JsonPerProp>>) -> String {
    match m {
        None => "None".into(),
        Some(map) if map.is_empty() => "None".into(),
        Some(map) => {
            let pairs = map
                .iter()
                .map(|(k, v)| {
                    format!(
                        "({k:?}.into(), PerPropTransition {{ duration: {} }})",
                        emit_opt_f32(v.duration)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("Some(HashMap::from([{pairs}]))")
        }
    }
}

fn emit_keyframe_value(v: &Value) -> String {
    match v {
        Value::Null => "KeyframeValue::Null".into(),
        Value::Bool(b) => format!("KeyframeValue::Bool({b})"),
        Value::Number(n) => {
            if let Some(f) = n.as_f64() {
                format!("KeyframeValue::Number({f}_f32)")
            } else {
                format!("KeyframeValue::String({:?}.into())", n.to_string())
            }
        }
        Value::String(s) => format!("KeyframeValue::String({s:?}.into())"),
        Value::Array(arr) => {
            let items = arr.iter().map(emit_keyframe_value).collect::<Vec<_>>().join(", ");
            format!("KeyframeValue::Array(vec![{items}])")
        }
        Value::Object(_) => format!("KeyframeValue::String({:?}.into())", v.to_string()),
    }
}
