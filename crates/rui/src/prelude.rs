//! 默认应用入口：`use rui::prelude::*;`
//!
//! # 双书写面（ADR-9）
//!
//! 本模块**同时** re-export：
//! - RSX / 标签入口（PascalCase：`Button`、`Input`、`Dialog`…）
//! - 等价 Builder / `fn`（`button`、`input`、`dialog`…）
//!
//! 禁止把 prelude 做成「只含标签」或「只含 Builder」。低层浮层几何
//! （[`crate::utils::popup`]）与私有壳（[`crate::components::internal`]）**不**进 prelude。
//!
//! # 不进本模块
//!
//! | 排除 | 原因 |
//! |------|------|
//! | `utils::popup::*`、`mark_floating` / placement | 低层能力；按需 `use rui::utils::popup` |
//! | `utils::anchored_overlay` / `viewport_modal` | 浮层编排壳；显式 `use rui::utils::anchored_overlay` |
//! | `popover_panel` | 低层面板；复合面用 `popover` / `Popover*` |
//! | `overlay` | 原语能力层，非默认产品面 |
//! | `path` 核（`PathCommand` / tessellate） | 原语能力层；公开面是 [`svg`] / Chart |
//! | `BaseComponentBuilder`、`apply_bound_*`、信号键 helpers | 进阶 / 内部契约 |
//! | `planned` 未落地组件（Spinner / Alert…） | 尚未 `pub use`；Skeleton / Badge 已导出 |
//!
//! # 示例
//!
//! ```ignore
//! use rui::prelude::*;
//!
//! // A · 标签
//! let _a = ui! { <Button variant="outline">"保存"</Button> };
//! let _badge = ui! { <Badge variant="secondary">"New"</Badge> };
//!
//! // B · Builder
//! let _b: Element = button("save").variant("outline").into();
//! let _b2: Element = badge().variant("destructive").text("Error").into();
//!
//! // 互嵌：标签树里嵌入 Builder
//! let _c = ui! {
//!     <VStack gap="0.5rem">
//!         { Element::from(button("x").variant("ghost").text("内嵌 Builder")) }
//!         <Button>"标签子节点"</Button>
//!         { Element::from(badge().text("内嵌 Badge")) }
//!     </VStack>
//! };
//!
//! // 互嵌：Builder 树里嵌入 ui!（拆文件 / 深嵌套同样安全：
//! // 每个 `ui!` 与 `#[component]` 在独立栈帧上构建，`run` 按需扩栈。）
//! let _d: Element = vstack()
//!     .gap("0.5rem")
//!     .child(ui! { <Label>"内嵌标签"</Label> })
//!     .child(ui! { <Badge variant="outline">"ok"</Badge> })
//!     .into();
//! ```

