fn main() {
    let manifest_dir = std::path::PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"),
    );
    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let json_path = manifest_dir.join("../rui/assets/lucide.json");

    println!("cargo:rerun-if-changed={}", json_path.display());

    let json = std::fs::read_to_string(&json_path).unwrap_or_else(|e| {
        panic!("failed to read {}: {e}", json_path.display());
    });
    let map: std::collections::BTreeMap<String, String> =
        serde_json::from_str(&json).unwrap_or_else(|e| {
            panic!("failed to parse lucide.json: {e}");
        });

    let mut builder = phf_codegen::Map::new();
    for (key, value) in &map {
        builder.entry(key, &serde_json::to_string(value).expect("glyph hex literal"));
    }
    let body = builder.build();
    let src = format!(
        "// @generated by build.rs — do not edit\n\
         pub(crate) static LUCIDE_GLYPH_HEX: phf::Map<&'static str, &'static str> =\n{body};\n"
    );
    std::fs::write(out_dir.join("lucide_glyph_hex.rs"), src).expect("write lucide_glyph_hex");
}
